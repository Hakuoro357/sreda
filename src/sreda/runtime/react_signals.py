# ── #288 (возврат механизма #180 «не хватает инфо — спроси, особенно ВРЕМЯ»): упоминание ВРЕМЕНИ
# (не даты!) в тексте хода. Гейтит schedule_reminder/update_reminder(время) на диспатче: конкретный
# момент в аргументе при отсутствии времени в тексте юзера → структурный отказ, НЕ создание.
# Проходит: «в 9», «в 13:00», «9.30», «в девять (утра)», «в час дня», «через час/30 минут»,
# «в полдень/полночь», части суток («утром/вечером» — бытовая конвенция, решение владельца 2026-07-09).
# НЕ время (гейтится): голая дата — «завтра», «14 числа», «9 июля», «в пятницу», «на след. неделе».
_TIME_WORD_HOURS = (
    "час|два|три|четыре|пять|шесть|семь|восемь|девять|десять|одиннадцать|двенадцать"
)
_MONTHS = r"янв|фев|март|мар|апр|ма[яй]|июн|июл|авг|сент|сен|окт|нояб|ноя|дек"
_TIME_RE = re.compile(
    r"(?:"
    # R2 (субагент MAJOR-1): точка-форма dd.mm — ДАТА («напомни 08.07»)! Двоеточие — всегда время;
    # точка — время только при минутах >12 (9.30/19.45; «9.10» остаточно гейтится — документировано).
    r"\b\d{1,2}:\d{2}\b"                                      # 13:00
    r"|\b\d{1,2}\.(?:1[3-9]|[2-5]\d)\b"                       # 9.30 / 19.45 (НЕ 08.07)
    # R2 (Codex «в 9-е»): дефис-порядковые — даты; месяц/«числа» — даты.
    # R3 (Codex high R2): `(?!\.\d)` — «в 08.07»/«к 09.07» это ДАТА, «в 08» до точки не открывает гейт
    # (валидное «в 19.30» проходит верхним точка-правилом по минутам >12).
    rf"|\bв\s+\d{{1,2}}\b(?!-)(?!\.\d)(?!\s*(?:час[ао]в?\s+)?(?:числ|{_MONTHS}))"  # «в 9» (НЕ «в 9 июля»/«в 9-е»/«в 08.07»)
    rf"|\bк\s+\d{{1,2}}\b(?!-)(?!\.\d)(?!\s*(?:числ|{_MONTHS}))"  # R2: «к 18»; R3: НЕ «к 09.07»
    r"|\b\d{1,2}\s+час(?:а|ов)?\b"                            # «9 часов», «в 21 час»
    r"|\b\d{1,2}\s+(?:утра|вечера|дня|ночи)\b"                # R2 (субагент MAJOR-2): «10 утра» без «в»
    rf"|\bв\s+(?:{_TIME_WORD_HOURS})\b(?!\s*(?:числ|{_MONTHS}))"  # «в девять», «в час (дня)»
    # R2 (оба Codex MAJOR): «полтора» ТОЛЬКО с часами — «через полтора дня/месяца» = дата-сдвиг.
    r"|\bчерез\s+(?:\d+\s*)?(?:час|минут|полчаса)"            # «через час/30 минут/полчаса»
    r"|\bчерез\s+полтора\s+час"                               # «через полтора часа» (НЕ «полтора дня»)
    # R2/R3: «то же время»/«за N минут до» — явная ссылка на время (перенос без переспроса-петли).
    # «как было»/«как обычно» УБРАНЫ в R3 (оба Codex + субагент: restore/manner-чтения без времени).
    r"|\bто\s+же\s+время\b"
    r"|\bза\s+\d+\s*(?:минут|час[ао]?в?)?\s+до\b|\bза\s+(?:час|полчаса)\s+до\b"
    r"|\bв\s+пол(?:день|ночь)\b"
    r"|\b(?:утром|вечером|дн[её]м|ночью|с\s+утра|после\s+обеда|к\s+обеду|к\s+вечеру"
    r"|на\s+вечер|на\s+утро|под\s+вечер)\b"
    r")",
    re.IGNORECASE,
)

# #288 R3 (субагент R2 MAJOR-2): «через 2 дня»/«за 3 дня до» — ДЛИТЕЛЬНОСТЬ/сдвиг даты, а «N дня» в
# _TIME_RE — часы («завтра в 2 дня» = 14:00). Дурационные обороты вырезаем ДО матча токен-заменой
# (код, не lookbehind — R1-урок #285: fixed-width lookbehind пробивался разделителями).
_DURATION_STRIP_RE = re.compile(
    r"\b(?:через|за)\s+\d{1,2}\s+(?:дн(?:я|ей)|ноч(?:и|ей)|недел\w*|месяц\w*)\b",
    re.IGNORECASE,
)


def text_mentions_time(text: str) -> bool:
    """#288: юзер называл ВРЕМЯ (не только дату) в этом тексте? False → инструменту напоминаний
    запрещено принимать конкретный момент (модель должна спросить «во сколько?»)."""
