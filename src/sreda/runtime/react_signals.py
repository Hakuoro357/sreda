"""#285 Фаза B срез B1: детерминированные сигнальные детекторы (чистые функции).

Единый путь ReAct, пилляр 1/3. Три детектора, калиброванные корпусами
(`plans/285-signal-corpora-v0.md`); тесты кодируют red-кейсы плана + состязательные
FP-классы из ревью R1 (`plans/285-B1-decisions.md`).

КОНТРАКТ ТОЧНОСТИ (пилляр 1, стр. 26/73): `write_command_signal`/`declarative_memory_signal`
гейтят ярус (а) = allowed_write БЕЗ confirm. **False-positive = молчаливая мутация** — высший
класс. Поэтому детекторы параноидальны; промахи (65% ходов, базлайн) ловит ярус (б) confirm.

**Граница B1↔B2 (связывающая, R1 субагент):** `write_command_signal` детектит ФОРМУ команды
(императив). Tier-(а) грант в B2 = `write_command_signal` И `route_domains` резолвит productivity
write-домен. Пример: «поставь чайник» → форма-команда True, но домена нет → B2 candidate/confirm,
НЕ молчаливая запись. То есть B1-сигнал НЕОБХОДИМ, но НЕ ДОСТАТОЧЕН для яруса (а) — домен-привязку
энфорсит B2 (иначе «поставь музыку» открыл бы write). read_cue false-positive дешевле (лишний read
в бюджете), но idiom-протечка исключена на уровне фразы.
"""

from __future__ import annotations

import re

# ── команды-мутации: ТОЛЬКО ИМПЕРАТИВ (ты/вы формы единообразно). Инфинитивы УБРАНЫ (R1 CRITICAL:
# «как добавить?», «надо купить» — вопрос/намерение, не команда; субагент подтвердил запуском, что
# императив-only ловит все позитивы). negative-lookbehind `(?<!не )` — «только не удали» не сигнал.
# Паразиты («удалось/удалились», «поставщик») отсекаются \b-границей (стем-императив ≠ форма паразита).
_CMD_VERBS = re.compile(
    r"(?<!не )\b("
    r"добавь(?:те)?|сохрани(?:те)?|запиши(?:те)?|запланируй(?:те)?"
    r"|внеси(?:те)?|отметь(?:те)?|вычеркни(?:те)?|поставь(?:те)?"
    r"|создай(?:те)?|отмени(?:те)?|перенеси(?:те)?|напомни(?:те)?"
    r"|запомни(?:те)?|заведи(?:те)?|удали(?:те)?|купи(?:те)?"
    r")\b",
    re.IGNORECASE,
)

# ── декларативные stable-fact паттерны (→ память, ярус (а) без confirm). Заглавная у ИМЕНИ/места
# отсекает near-miss («меня зовут на дачу», «живу надеждой»). Захват X → пост-проверка стоп-списком
# (R1 MAJOR: «живу в Интернете», «зовут Солнышко» — заглавное нарицательное). НЕ IGNORECASE — гард
# заглавной реально различает регистр.
_DECL_NAME = re.compile(r"\b[Мм]еня зовут\s+([А-ЯЁ][а-яё]+)")
_DECL_LIVE = re.compile(r"\b(?:[Яя]\s+)?[Жж]иву в\s+([А-ЯЁ][а-яё]+)")
_DECL_REL = re.compile(r"\b(?:мо(?:его|ю|ей)\s+)?(?:муж[аеу]?|жену?|сына?|доче?[рь]|дочку|"
                       r"кота|собаку|мам[уы]|пап[уы])\s+зовут\s+([А-ЯЁ][а-яё]+)")
_DECL_MYNAME = re.compile(r"\bмо[её]\s+имя\s+[—-]?\s*([А-ЯЁ][а-яё]+)")
_DECL_KIDS = re.compile(r"\b[Уу] меня\s+(?:двое|трое|четверо|пятеро|\d+)\s*(?:дет|реб|сын|доч)")

# стоп-список для захваченного X (best-effort; остаток — петля калибровки Фазы F). Соцсети/абстракции
# (для «живу в X») + родств.-обращения/ласкательные (для «зовут X»).
_DECL_STOP = frozenset({
    "интернете", "твиттере", "инстаграме", "фейсбуке", "телеграме", "тиктоке", "ютубе", "сети",
    "аду", "раю", "ожидании", "надежде", "мечтах", "мечте", "долгу", "прошлом", "будущем", "моменте",
    "мама", "папа", "солнышко", "зайка", "зайчик", "котик", "дорогой", "дорогая", "милый", "милая",
})

# ── read-кюсы → bounded домены (щедро; цена ошибки — лишний read в бюджете, пилляр 3). Голый «дела»
# УБРАН (R1 MAJOR: «дела идут в гору» → own-data; «как дела» — идиома). Кюсы — в ЗАПРОСНОЙ рамке;
# «как дела с задачами» ловится кюсом «задач» → {tasks} (идиома-регекс больше не нужна).
_READ_CUES: tuple[tuple[re.Pattern[str], frozenset[str]], ...] = (
    (re.compile(r"\bнапоминани", re.IGNORECASE), frozenset({"reminders"})),
    (re.compile(r"\bзадач(?!ник|к)", re.IGNORECASE), frozenset({"tasks"})),
    # checklists/дела — ТОЛЬКО в запросной рамке (не голое «дела»)
    (re.compile(r"\b(?:покажи|мои|наши|какие)\s+дел|\bсписок\s+дел|\bчто\s+с\s+делами"
                r"|\bдел[аоы]?\s+на\s|\bчеклист|\bчек-лист", re.IGNORECASE),
     frozenset({"checklists"})),
    (re.compile(r"\b(?:в\s+списк|список\s+покупок|мой\s+список|список\s+дел|что\s+в\s+списк)",
                re.IGNORECASE), frozenset({"checklists", "shopping"})),
    (re.compile(r"\bпокупк", re.IGNORECASE), frozenset({"shopping"})),
    # память: own-data lookup — «помнишь» (2л, не «помню»); явные own-data обороты
    (re.compile(r"\b(?:как\s+меня\s+зовут|помни(?:шь|те)|что\s+я\s+(?:говорил|рассказыв)"
                r"|что\s+у\s+меня\s+записано|мо[её]\s+имя)", re.IGNORECASE),
     frozenset({"memory"})),
    (re.compile(r"\bменю\b", re.IGNORECASE), frozenset({"menu"})),
    (re.compile(r"\bрецепт(?!\s+(?:счастья|успеха|жизни))", re.IGNORECASE), frozenset({"recipes"})),
)


def write_command_signal(text: str) -> bool:
    """Есть ли ЯВНАЯ ИМПЕРАТИВНАЯ команда-мутация (ФОРМА). B1-сигнал НЕОБХОДИМ, но НЕ ДОСТАТОЧЕН для
    яруса (а): B2 дополнительно требует productivity write-домен от route_domains (иначе «поставь
    чайник» открыл бы write). High-precision по форме: инфинитив/вопрос/отрицание → False."""
    return bool(_CMD_VERBS.search(text or ""))


def declarative_memory_signal(text: str) -> bool:
    """Декларативный stable-fact о себе (→ save_core_fact без confirm). near-miss отсечён заглавной;
    заглавное нарицательное («живу в Интернете», «зовут Солнышко») — стоп-списком."""
    t = text or ""
    if _DECL_KIDS.search(t):
        return True
    for pat in (_DECL_NAME, _DECL_LIVE, _DECL_REL, _DECL_MYNAME):
        m = pat.search(t)
        if m and m.group(1).lower() not in _DECL_STOP:
            return True
    return False


def read_cue_domains(text: str) -> frozenset[str]:
    """Щедрый кюс→bounded read-домены (пилляр 3). Голый «дела»/идиома → пусто (не own-data read).
    Пусто = baseline (web без own-data, решает B2). Возврат — объединение доменов совпавших кюсов."""
    t = text or ""
    out: set[str] = set()
    for pat, doms in _READ_CUES:
        if pat.search(t):
            out |= doms
    return frozenset(out)
