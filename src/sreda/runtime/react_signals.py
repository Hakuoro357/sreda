# meta/quote-гард (R2 CodexH CRITICAL): цитируемый/обсуждаемый/пересказанный императив ≠ команда.
# Домен у таких фраз ЕСТЬ («команда "добавь молоко" не работает» → shopping), поэтому B2-домен-гейт
# их НЕ ловит — нужен guard в B1. Over-suppress безопасен (промах → ярус (б) confirm).
# Глаголы косвенной речи/поручения — общий алфавит для рамки ДО и ПОСЛЕ совпадения (R5 CodexH/субагент:
# «добавь молоко, сказал он» — атрибуция ПОСЛЕ обходила before-only guard).
_REPORTED = (
    r"сказал\w*|говор(?:ит|ил\w*)|пишет|написа\w*|гласит|цитир\w*|спросил\w*|ответил\w*"
    r"|(?:по)?просил\w*|просит|велел\w*|велит|приказал\w*|приказывает|предложил\w*|предлагает"
    r"|(?:по)?советовал\w*|советует|напомнил\w*|напоминает|требует|требовал\w*|представил\w*"
)
_META_BEFORE = re.compile(
    r"\b(?:слов\w*|фраз[аыуе]|команд[аыуе]|значит|означа|перевед\w*|перевес\w*|перевод"
    r"|как\s+сказать|что\s+значит|почему|зачем|" + _REPORTED + r")\b",
    re.IGNORECASE,
)
# рамка-атрибуция ПОСЛЕ совпадения: «…, сказал он» / «…, попросила мама» (R5). Требуем запятую перед
# глаголом речи (иначе далёкий «сказал» в другой клаузе ложно глушил бы команду).
_REPORTED_AFTER = re.compile(r",\s*(?:" + _REPORTED + r")\b", re.IGNORECASE)
_QUOTE = re.compile(r"[«»\"“”„‘’]")
# реплика/ярлык говорящего перед совпадением: «мама: удали…», «он мне: удали…» (B2 R5 CodexH —
# reported-речь без глагола, только двоеточие). Двоеточие в хвосте before → цитируемая реплика.
_DIALOGUE_COLON = re.compile(r":\s*$")
# R2 CodexM: «напомни, как меня зовут» — «напомни» write-глагол, но WH-фрейм = ЧИТАТЕЛЬСКИЙ запрос
# (напомни/скажи мне ЧТО/КАК/КТО…, не создать напоминание). Только «напомни» (не «запомни» — там
# «запомни, какой у меня рост» = write). Over-suppress безопасен (промах → ярус (б) confirm).
_REMIND_READ_FRAME = re.compile(
    r"\bнапомни\w*\s*,?\s+(?:как|что|кто|где|когда|сколько|каком|какой|какая|какие|почему)\b",
    re.IGNORECASE,
)


def _framed(text: str, start: int, end: int) -> bool:
    """Совпадение [start:end) отрицается/обсуждается/цитируется → НЕ прямой сигнал (общий guard
    команд и деклараций, R4 CodexH: декларации тоже подвержены meta/quote/reported-речи)."""
    before, after = text[:start], text[end:]
    if _NEG_BEFORE.search(before):  # «не» (любой разделитель) перед совпадением
        return True
    if _META_BEFORE.search(before):  # мета-рамка/косвенная речь/просьба перед совпадением
        return True
    if _DIALOGUE_COLON.search(before):  # «мама: удали…» — реплика/ярлык говорящего (B2 R5 CodexH)
        return True
    if _REPORTED_AFTER.search(after):  # атрибуция ПОСЛЕ: «…, сказал он» (R5 CodexH/субагент)
        return True
    if _QUOTE.search(before) and _QUOTE.search(after):  # совпадение в кавычках → цитата
        return True
    return False


def write_command_signal(text: str) -> bool:
    """Есть ли ЯВНАЯ ИМПЕРАТИВНАЯ команда-мутация (ФОРМА). B1-сигнал НЕОБХОДИМ, но НЕ ДОСТАТОЧЕН для
    яруса (а): B2 дополнительно требует productivity write-домен от route_domains (иначе «поставь
    чайник» открыл бы write). High-precision по форме: инфинитив/вопрос/отрицание/цитата/косвенная
    речь/напомни-WH-фрейм → False."""
    t = text or ""
    if _REMIND_READ_FRAME.search(t):  # «напомни, как меня зовут» = читательский фрейм, не write
        return False
    # хотя бы ОДИН чистый императив (не отрицаемый/не мета/не цитата). finditer → «не удали, но
    # добавь молоко»: «удали» отрицаемо (skip), «добавь» чистое → True (recall не теряется).
    return any(not _framed(t, m.start(), m.end()) for m in _CMD_VERBS.finditer(t))


# ── #316 R4/R5 (Codex high/medium R3-R4 MAJOR): голый императив-ЭХО на confirm-паузе. «удали»/«ок удали»/
# «удали пожалуйста»/«ну давай удали»/«отмени» = слова-филлеры (частицы согласия/вежливости/дискурсивные)
# + ОДИНОКИЙ командный глагол без объекта → ДВУСМЫСЛЕННОЕ подтверждение действия паузы, НЕ новый запрос.
# #267 A0 трактует такое безопасным «нет» (fail-closed удаления); #316 без гейта делал abandon+fresh (хуже:
# re-confirm-петля на голосе). «удали задачу B»/«удали покупки»/«удали всё» (есть объект) → НЕ эхо, редирект.
# R5 (оба Codex): токенный подход — выкинуть ВСЕ филлеры и пунктуацию ОТОВСЮДУ (не только ведущие) → закрыть
# хвостовые формы «удали пожалуйста»/«удали,» одним махом, а не латать по одной. Местоимения-указатели
# (это/его/их) и модальные (может/всё) НЕ филлеры (могут быть объектом) → осознанный residual (промах
# безопасен: направление = лишний redirect, не потеря; delete всё равно fail-closed за confirm).
_ECHO_FILLER = frozenset({
    "ок", "окей", "ладно", "ну", "давай", "давайте", "да", "нет", "хорошо", "конечно",
    "угу", "ага", "пожалуйста", "плиз", "спасибо", "же", "ка", "уж", "уже", "тогда",
    # #362 R2 (Codex sol+terra MINOR): выровнять с _LEAD_FILLERS — нейтральный дискурс-филлер = noise
    # (голое «ой»/«вот»/«эх» на confirm → resume/fail-closed, а не редирект живой паузы).
    "ой", "вот", "эх",
})


def bare_command_echo(text: str) -> bool:
    """#316 R5: после отбрасывания филлеров (частицы согласия/вежливости/дискурсивные) и пунктуации
    остаётся РОВНО один write-глагол без объекта? True → эхо-подтверждение на confirm-паузе (не новый
    запрос). «удали»/«ок удали»/«удали пожалуйста»/«ну давай удали»/«отмени»/«удали,» → True; «удали
    задачу B»/«удали покупки» → False (объект); «покажи покупки» → False (не write-глагол)."""
    t = re.sub(r"[^\w\s]", " ", (text or "").lower())  # пунктуация → пробел (\w Unicode — кириллица ок)
    toks = [w for w in t.split() if w not in _ECHO_FILLER]
    return len(toks) == 1 and bool(_CMD_VERBS.fullmatch(toks[0]))


# ── #362 R3→R5 (Codex sol+terra, конвергентно): ПРОТОКОЛ-СЕМАНТИКА confirm-паузы. У confirm-паузы
# валидны ТОЛЬКО «да»/«нет» — свободных СЛОТ-ответов НЕТ. Значит ЛЮБАЯ СОДЕРЖАТЕЛЬНАЯ не-да/нет реплика
