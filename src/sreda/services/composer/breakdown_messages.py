"""Пул «весёлых поломок» — правило Бориса (2026-06-11).

Любой ТЕХНИЧЕСКИЙ отказ пользователю («любой чих»: невалидный план,
ошибка сборки, запрет показа, падение инструмента) — живое сообщение
«у меня внутри что-то сломалось, создатели уже чинят», случайное из
пула. Сухие технические отказы («не могу безопасно показать результат»,
«не получилось обработать запрос») у пользователя НЕ появляются.

НЕ поломки (пул не применять): уточнения, пустые списки, честная
неопределённость записи (_FALLBACK_UNCERTAIN), частичный успех
(partial_with_compose_error — там есть содержательная часть).

Второе правило той же даты: «пользователь увидел ошибку → она записана
у нас». Каждая точка, отдающая фразу из пула, обязана зафиксировать
событие — ``note_breakdown()`` (ERROR-лог + admin-алерт с дедупом).
"""
from __future__ import annotations

import logging
import random

logger = logging.getLogger(__name__)

BREAKDOWN_POOL: tuple[str, ...] = (
    "Ой… у меня внутри что-то заело 🙈 Создатели уже разбираются. "
    "Попробуй ещё разок через минутку!",
    "Кажется, я споткнулась о собственный провод 🛠 Мастера уже в курсе "
    "и чинят. Повтори, пожалуйста, чуть позже.",
    "Что-то у меня шестерёнки заскрипели… Создателям уже пожаловалась — "
    "чинят. Давай попробуем ещё раз через минутку?",
    "Уф, тут у меня маленькая поломка 🧰 Создатели уже бегут с отвёрткой. "
    "Вернусь в строй совсем скоро — повтори чуть позже!",
    "Прости, я тут немножко сломалась 💔 Создатели уже знают и чинят. "
    "Попробуй снова через пару минут!",
)


def breakdown_phrase() -> str:
    """Случайная фраза пула — живой голос вместо сухого отказа."""
    return random.choice(BREAKDOWN_POOL)


def note_breakdown(source: str, detail: str = "", *, alert: bool = True) -> None:
    """Фиксация показанной пользователю поломки на НАШЕЙ стороне.

    ERROR-лог (всегда) + P1 admin-алерт (fire-and-forget, дедуп по
    source). ``alert=False`` — для путей, где рядом УЖЕ уходит свой
    алерт (например ``planner_chat._alert`` стадии): лог обязателен,
    второй алерт владельцу — дубль. Никогда не поднимает исключений —
    фиксация не должна добавить второй сбой к первому."""
    logger.error("ПОЛОМКА показана пользователю: %s %s", source, detail[:200])
    if not alert:
        return
    try:
        from sreda.services.admin_alerts import send_admin_alert
        send_admin_alert(
            "P1",
            f"пользователь увидел поломку: {source}",
            detail[:400] or source,
            dedupe_key=f"breakdown:{source}",
        )
    except Exception:  # noqa: BLE001 — алерт не стоит второго сбоя
        logger.exception("note_breakdown: alert delivery failed")


__all__ = ["BREAKDOWN_POOL", "breakdown_phrase", "note_breakdown"]
