# ───────── write_command_signal: позитивы (ярус (а) обязан сработать) ─────────
@pytest.mark.parametrize("text", [
    "добавь молоко",
    "добавь молоко в покупки",
    "сохрани рецепт борща",
    "запиши это",
    "запиши, что я обещал позвонить",
    "запланируй встречу на завтра в 10",
    "внеси поход к врачу в план",
    "отметь молоко купленным",
    "вычеркни молоко",
    "поставь напоминание про смесь",
    "напомни позвонить маме",
    "запомни что я не ем глютен",
    "удали напоминание",
    "удали задачу про хлеб",
    "отмени задачу",
    "перенеси встречу на пятницу",
    "создай список покупок",
    "купи молока",
])
def test_write_command_positive(text):
    assert write_command_signal(text) is True, text


# ───────── write_command_signal: негативы (смолток/факт/near-miss — НЕ сигнал) ─────────
@pytest.mark.parametrize("text", [
    "как дела?",
    "что нового?",
    "как жизнь?",
    "как ты?",
    "доброе утро",
    "спасибо, умница",
    "расскажи анекдот",
    "кто написал Войну и мир?",
    "что в списке?",           # read, не write
    "перескажи напоминания",   # read, не write
    "не удалось открыть дверь",   # паразит «удал»
    "мы удалились со встречи",     # паразит «удал»
    "поставщик задерживает",       # паразит «постав»
    "меня зовут на дачу в выходные",  # near-miss декларации (не команда)
    # R1 CRITICAL (оба Codex + субагент): инфинитив в вопросе/намерении/нарративе — НЕ команда
    "как удалить задачу?",
    "можно добавить молоко?",
    "надо купить молоко",
    "хочу сохранить рецепт",
    "купить бы молока",
    "отменить подписку сложно",
    "стоит ли сохранить чек",
    "мне нужно купить лекарство",
    "забыл записать адрес",
    "нечего добавить",
    "не могу удалить фото",
    # R1 MAJOR (субагент): отрицание «не <перфектив-императив>» — просьба воздержаться
    "только не удали случайно",
    "не отмени встречу",
    "не запиши лишнего",
    # R2 CRITICAL (оба Codex): цитируемый/мета/косвенный императив — домен есть, но это НЕ команда
    'команда "добавь молоко" не работает',
    'что значит "удали задачу"?',
    'почему фраза "создай список покупок" опасна?',
    "как перевести удали задачу",
    "он сказал: добавь молоко",
    "она говорит запиши это",
    # R2 CRITICAL (CodexM): «напомни, <WH>» — читательский фрейм, не создание напоминания
    "напомни, как меня зовут",
    "напомни как меня зовут",
    "напомни, что я обещал",
])
def test_write_command_negative(text):
    assert write_command_signal(text) is False, text


# ───────── write_command_signal: позитивы, которые guard-ы НЕ должны сломать ─────────
@pytest.mark.parametrize("text", [
    "запомни, что я не ем глютен",   # «запомни, что» = write (не WH-read как «напомни»)
    "напомни купить молоко",          # напомни + инфинитив-объект = write-напоминание
    'добавь "молоко" в список',       # кавычки только у объекта (после глагола) = команда
    "пожалуйста, добавь молоко",      # вежливая рамка — команда
    "слушай, запиши это",             # обращение — команда
    "не удали задачу, а добавь молоко",  # отрицание у одного глагола, чистая команда у другого
])
def test_write_command_positive_not_broken_by_guards(text):
    assert write_command_signal(text) is True, text


@pytest.mark.parametrize("text", [
    "не  удали задачу",       # два пробела — разделитель-обход lookbehind (R2 субагент MAJOR)
    "не\tудали задачу",       # табуляция
    "не   отмени встречу",    # три пробела
    "больше не добавляй",     # несовершенный вид (форма другая, но проверим)
])
def test_write_command_negation_separator_holds(text):
    assert write_command_signal(text) is False, text


# ───────── write_command_signal: императивная ФОРМА-команда True, но B2 гейтит по домену ─────────
@pytest.mark.parametrize("text", [
    "поставь чайник",
    "поставь музыку",
    "создай атмосферу",
    "отметь про себя",
])
def test_write_command_imperative_form_true_b2_gates_domain(text):
    """R1 субагент CRITICAL→MAJOR (контракт B1↔B2): императив = ФОРМА-команда (True), но
    productivity-домена нет → B2 (route_domains) НЕ грантит allowed_write → candidate/confirm,
    НЕ молчаливая запись. B1 детектит форму; домен-привязку энфорсит B2 (285-B1-decisions.md B)."""
    assert write_command_signal(text) is True, text


